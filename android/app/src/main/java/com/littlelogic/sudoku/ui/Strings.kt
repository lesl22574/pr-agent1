fun stringsFor(language: Language): Strings =
    if (language == Language.EN) EnglishStrings else RussianStrings

fun messageText(key: MessageKey, strings: Strings): String = when (key) {
    MessageKey.NOTES_ON -> strings.notesOn
    MessageKey.NOTES_OFF -> strings.notesOff
    MessageKey.SELECT_CELL -> strings.selectCell
    MessageKey.FIXED_CELL -> strings.fixedCell
    MessageKey.NO_HINTS -> strings.noHints
    MessageKey.NO_MOVES -> strings.noMoves
}
